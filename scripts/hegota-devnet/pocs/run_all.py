#!/usr/bin/env python3
"""Run every scenario, then regenerate EVIDENCE.md from the recorded runs.

Exits non-zero if any scenario fails. Every figure in EVIDENCE.md comes from a JSON
evidence record written by an actual run — nothing is hand-copied, so a claim that cannot
be reproduced disappears from the document rather than going stale.

Note on the faucet: the devnet faucet rate-limits per address, so a full back-to-back run
may need to wait for a top-up. Individual scenarios can be run on their own.
"""
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
EVIDENCE_DIR = os.path.join(HERE, "evidence")
OUT = os.path.abspath(os.path.join(HERE, "..", "EVIDENCE.md"))

SCENARIOS = [
    ("poc0_guard_provenance.py", "P0", "Guard provenance — the assertion cannot be stripped"),
    ("poc1_approval_drain.py", "P1", "Hidden unlimited approval with a delayed drain"),
    ("poc6_proxy_swap.py", "P6", "Implementation swapped before inclusion, and two assertion traps"),
    ("poc7_allowance_elimination.py", "P7", "Standing-allowance elimination"),
]


def run(script):
    print(f"\n### running {script}")
    return subprocess.run([sys.executable, os.path.join(HERE, script)]).returncode == 0


def render():
    records = {}
    for f in sorted(os.listdir(EVIDENCE_DIR)) if os.path.isdir(EVIDENCE_DIR) else []:
        if f.endswith(".json"):
            records[f[:-5]] = json.load(open(os.path.join(EVIDENCE_DIR, f)))
    if not records:
        print("no evidence records found; not writing EVIDENCE.md")
        return

    L = []
    L.append("# Evidence")
    L.append("")
    L.append("Generated by `pocs/run_all.py` from the JSON records in `pocs/evidence/`. Every")
    L.append("figure below comes from an actual run against the public devnet; nothing here is")
    L.append("hand-written. Re-running regenerates it.")
    L.append("")
    L.append("**Reading a defended transaction.** A POST_TX assertion that fires invalidates the")
    L.append("whole transaction, so it is *excluded from the block*: there is no receipt and no")
    L.append("explorer page for a successful defense. \"admitted, never mined\" plus unchanged")
    L.append("victim state IS the positive result. See `pocs/GATE-RESULTS.md` for why simulation")
    L.append("cannot be used to identify which assertion tripped.")
    L.append("")

    for key in sorted(records):
        r = records[key]
        L.append(f"## {r['scenario']} — {r['title']}")
        L.append("")
        L.append(f"- **Models:** {r['models']}")
        L.append(f"- **Defense kind:** {r['defense_kind']}")
        L.append(f"- **Chain id:** {r['chain_id']} · **from block:** {r['started_block']}")
        L.append("")
        if r.get("addresses"):
            L.append("| contract | address |")
            L.append("|---|---|")
            for k, v in r["addresses"].items():
                L.append(f"| {k} | `{v}` |")
            L.append("")
        for phase in ("phase_a", "phase_b", "extra"):
            if r.get(phase):
                L.append(f"**{phase.replace('_', ' ')}**")
                L.append("")
                L.append("```json")
                L.append(json.dumps(r[phase], indent=2))
                L.append("```")
                L.append("")
        if r.get("notes"):
            L.append("**Findings**")
            L.append("")
            for n in r["notes"]:
                L.append(f"- {n}")
            L.append("")

    with open(OUT, "w") as f:
        f.write("\n".join(L) + "\n")
    print(f"\nwrote {os.path.relpath(OUT)} from {len(records)} record(s)")


def main():
    only = sys.argv[1:] or None
    failed = []
    for script, tag, _ in SCENARIOS:
        if only and tag not in only and script not in only:
            continue
        if not run(script):
            failed.append(script)
    render()
    if failed:
        print(f"\nFAILED: {', '.join(failed)}")
        return 1
    print("\nall scenarios passed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
